'use strict';
const assert=require('node:assert/strict'),W=require('../core/water-routing');
assert.equal(W.candidates('').status,'NEEDS_REGION');
assert.equal(W.candidates('hcm','longan-old').status,'INVALID_AREA');
assert.equal(W.candidates('tayninh','longan-old').providers[0].id,'lawaco');
assert.equal(W.candidates('hcm','binhduong-old').status,'CANDIDATES_ONLY');
assert.equal(W.candidates('hcm','brvt-old').status,'CANDIDATES_ONLY');
assert.equal(W.candidates('tayninh','tayninh-old').status,'CANDIDATES_ONLY');
for(const [region,providerId] of [['hcm','lawaco'],['tayninh','sawaco']])assert.equal(W.resolve({region,providerId,confirmed:true}).apps.length,0);
for(const confirmed of [false,'true',1,undefined])assert.equal(W.resolve({region:'tayninh',area:'longan-old',providerId:'lawaco',confirmed}).apps.length,0);
const ready=W.resolve({region:'tayninh',area:'longan-old',providerId:'lawaco',confirmed:true});
assert.equal(ready.status,'HANDOFF_READY');assert.equal(ready.canConfirmPayment,false);assert.deepEqual(ready.apps.map(x=>x.id),['payoo']);
assert.deepEqual(W.fromQuery('tiền nước Long An'),{region:'tayninh',area:'longan-old'});
assert.deepEqual(W.fromQuery('nước TP.HCM và Tây Ninh'),{region:'',area:''});
assert.equal(W.launchRequest('javascript:evil',{openKnownApp(){throw Error('Should never call');}}).status,'UNKNOWN_APP');
assert.equal(W.launchRequest('momo',null).status,'NATIVE_LAUNCH_UNAVAILABLE');
let calls=[];const bridge={openKnownApp(id){calls.push(id);return 'REQUESTED';}};
assert.equal(W.launchRequest('momo',bridge).status,'LAUNCH_REQUESTED');assert.deepEqual(calls,['momo']);
assert.equal(W.launchRequest('payoo',{openKnownApp:()=> 'NOT_INSTALLED'}).status,'NOT_INSTALLED');
assert.equal(W.launchRequest('payoo',{openKnownApp(){throw Error('native failure');}}).status,'LAUNCH_FAILED');
console.log('PASS water: regions, candidates vs confirmed provider, unsupported rural areas, pinned app dispatch and no false payment result.');
